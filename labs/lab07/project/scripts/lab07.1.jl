using Pkg
Pkg.activate("../project")
using DrWatson
@quickactivate "project"

using DifferentialEquations
using Plots

# ==============================================================================
# 1. Исходные данные и параметры Варианта 19 (по тексту задания)
# ==============================================================================
const N = 1003         # Объем аудитории
const n0 = 7           # В начальный момент о товаре знает 7 человек
const tspan = (0.0, 30.0) # Общий временной промежуток

# Параметры уравнений
const alpha1_1 = 0.67
const alpha2_1 = 0.00004

const alpha1_2 = 0.00006
const alpha2_2 = 0.72

# Динамические коэффициенты для Случая 3
alpha1_3(t) = 0.3 * cos(3*t)
alpha2_3(t) = 0.2 * cos(2*t)

# Вектор начальных условий (Float64)
u0 = [Float64(n0)]

# ==============================================================================
# 2. Определение систем дифференциальных уравнений
# ==============================================================================

# Случай 1
function ad_case1!(du, u, p, t)
    n = u[1]
    du[1] = (alpha1_1 + alpha2_1 * n) * (N - n)
end

# Случай 2
function ad_case2!(du, u, p, t)
    n = u[1]
    du[1] = (alpha1_2 + alpha2_2 * n) * (N - n)
end

# Случай 3
function ad_case3!(du, u, p, t)
    n = u[1]
    du[1] = (alpha1_3(t) + alpha2_3(t) * n) * (N - n)
end

# ==============================================================================
# 3. Численное решение ОДУ
# ==============================================================================

# Случай 1 (Гладкое стандартное решение)
prob1 = ODEProblem(ad_case1!, u0, tspan)
sol1 = solve(prob1, Tsit5(), saveat=0.1)

# Случай 2 (Жесткая система из-за сильного эффекта сарафанного радио alpha2 = 0.72)
prob2 = ODEProblem(ad_case2!, u0, tspan)
sol2 = solve(prob2, Rosenbrock23(), saveat=0.0001)

# Случай 3 (Динамическая система, ограничиваем время симуляции, т.к. насыщение полное)
prob3 = ODEProblem(ad_case3!, u0, (0.0, 2.0))
sol3 = solve(prob3, Rosenbrock23(), saveat=0.001)

# ==============================================================================
# 4. Визуализация и сохранение графиков (Задание 1)
# ==============================================================================
default(titlefont=font(10, "Computer Modern"),
        guidefont=font(9, "Computer Modern"),
        tickfont=font(8, "Computer Modern"))

# График 1: платная реклама доминирует (процесс занимает около 10-15 единиц времени)
plt1 = plot(sol1, xlims=(0.0, 15.0), ylims=(0, N*1.05),
            title="Эффективность рекламы: Случай 1",
            xlabel="Время t", ylabel="Число информированных n(t)",
            label="n(t)", color=:blue, lw=2, legend=:bottomright)
savefig(plt1, plotsdir("task1_case1.png"))

# График 2: доминирует сарафанное радио (рост лавинообразный, смотрим масштаб до t=0.02)
plt2 = plot(sol2, xlims=(0.0, 0.02), ylims=(0, N*1.05),
            title="Эффективность рекламы: Случай 2",
            xlabel="Время t", ylabel="Число информированных n(t)",
            label="n(t)", color=:red, lw=2, legend=:bottomright)
savefig(plt2, plotsdir("task1_case2.png"))

# График 3: периодические коэффициенты (смотрим масштаб до t=0.1)
plt3 = plot(sol3, xlims=(0.0, 0.1), ylims=(0, N*1.05),
            title="Эффективность рекламы: Случай 3",
            xlabel="Время t", ylabel="Число информированных n(t)",
            label="n(t)", color=:purple, lw=2, legend=:bottomright)
savefig(plt3, plotsdir("task1_case3.png"))

using DifferentialEquations, DataFrames

# Структура для хранения параметров моделей двух фирм
struct CompetitionParams
    p_cr::Float64   # Критическая стоимость продукта
    τ1::Float64     # Длительность производственного цикла фирмы 1
    p1::Float64     # Себестоимость продукта у фирмы 1
    τ2::Float64     # Длительность производственного цикла фирмы 2
    p2::Float64     # Себестоимость продукта у фирмы 2
    N::Float64      # Число потребителей (в тыс. единиц)
    q::Float64      # Максимальная потребность одного человека

    # Вычисляемые нормированные коэффициенты
    a1::Float64
    a2::Float64
    b::Float64
    c1::Float64
    c2::Float64

    # Конструктор для автоматического расчета коэффициентов
    function CompetitionParams(p_cr, τ1, p1, τ2, p2, N, q)
        a1 = p_cr / (τ1^2 * p1^2 * N * q)
        a2 = p_cr / (τ2^2 * p2^2 * N * q)
        b  = p_cr / (τ1 * τ2 * p1 * p2 * N * q)
        c1 = (p_cr - p1) / (τ1 * p1)
        c2 = (p_cr - p2) / (τ2 * p2)
        new(p_cr, τ1, p1, τ2, p2, N, q, a1, a2, b, c1, c2)
    end
end

# Уравнения для Случая 1: Чистая рыночная конкуренция
function case1_dynamics!(dM, M, p::CompetitionParams, t)
    dM[1] = (p.c1 / p.c1) * M[1] - (p.a1 / p.c1) * M[1]^2 - (p.b / p.c1) * M[1] * M[2]
    dM[2] = (p.c2 / p.c1) * M[2] - (p.a2 / p.c1) * M[2]^2 - (p.b / p.c1) * M[1] * M[2]
end

# Уравнения для Случая 2: С учетом социально-психологического фактора (дополнительное лоббирование)
function case2_dynamics!(dM, M, p::CompetitionParams, t)
    # Задаем коэффициент социально-психологического фактора (например, из методички ~ 0.002)
    s_factor = 0.0002
    dM[1] = (p.c1 / p.c1) * M[1] - (p.a1 / p.c1) * M[1]^2 - ((p.b / p.c1) + s_factor) * M[1] * M[2]
    dM[2] = (p.c2 / p.c1) * M[2] - (p.a2 / p.c1) * M[2]^2 - (p.b / p.c1) * M[1] * M[2]
end

# Функция для вычисления стационарного состояния первого случая (Задание 3)
function find_stationary_state(p::CompetitionParams)
    # Уравнения плоскостей баланса:
    # 1 - (a1/c1)*M1 - (b/c1)*M2 = 0  => a1*M1 + b*M2 = c1
    # (c2/c1) - (a2/c1)*M2 - (b/c1)*M1 = 0 => b*M1 + a2*M2 = c2

    # Матрица системы Линейных Алгебраических Уравнений (СЛАУ)
    A = [p.a1  p.b;
         p.b   p.a2]
    B = [p.c1, p.c2]

    # Решение системы методом Крамера/обратной матрицы
    M_stat = A \ B

    return M_stat # Возвращает [M1_stat, M2_stat]
end

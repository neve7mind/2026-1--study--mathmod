using Pkg
Pkg.activate("../project")
using DrWatson
@quickactivate "project"

using DifferentialEquations, Plots

# Подключаем ядро модели
include(srcdir("competition_model.jl"))

# Создаем папки для вывода, если их нет
mkpath(plotsdir())

# --- Инициализация параметров (Задание 1: Ваш уникальный пример фирм) ---
# Зададим базовые экономические параметры (можно немного изменить себестоимость)
p_cr_val = 20.0   # Критическая цена
τ1_val   = 10.0   # Цикл Фирмы 1
p1_val   = 9.0    # Себестоимость Фирмы 1
τ2_val   = 16.0   # Цикл Фирмы 2
p2_val   = 7.0    # Себестоимость Фирмы 2 (ниже себестоимость, но длиннее цикл)
N_val    = 10.0   # Рыночная ниша потребителей
q_val    = 1.0    # Интенсивность спроса

params = CompetitionParams(p_cr_val, τ1_val, p1_val, τ2_val, p2_val, N_val, q_val)

# Начальный капитал: Фирма 1 стартует с преимуществом (M1 = 2.0, M2 = 1.0)
M0 = [2.0, 1.0]
tspan = (0.0, 30.0)

# ------------------------------------------------------------------
# Моделирование СЛУЧАЯ 1 (Рыночная среда)
# ------------------------------------------------------------------
prob1 = ODEProblem(case1_dynamics!, M0, tspan, params)
sol1 = solve(prob1, RK4(), reltol=1e-8, abstol=1e-8)

# ------------------------------------------------------------------
# Моделирование СЛУЧАЯ 2 (Социально-психологический эффект)
# ------------------------------------------------------------------
prob2 = ODEProblem(case2_dynamics!, M0, tspan, params)
sol2 = solve(prob2, RK4(), reltol=1e-8, abstol=1e-8)

# ------------------------------------------------------------------
# Расчет стационарного состояния для Случая 1 (Задание 3)
# ------------------------------------------------------------------
M_stationary = find_stationary_state(params)
println("\n====================================================")
println("РЕЗУЛЬТАТЫ АНАЛИЗА СТАЦИОНАРНОГО СОСТОЯНИЯ (Случай 1):")
println("Стационарный объем оборотных средств Фирмы 1 (M1): ", round(M_stationary[1], digits=4))
println("Стационарный объем оборотных средств Фирмы 2 (M2): ", round(M_stationary[2], digits=4))
println("====================================================\n")

# ------------------------------------------------------------------
# Визуализация результатов (Задание 1)
# ------------------------------------------------------------------
# График 1: Случай 1
plt1 = plot(sol1, vars=(0, 1), label="Фирма 1 (M1)", color=:blue, lw=2.5)
plot!(plt1, sol1, vars=(0, 2), label="Фирма 2 (M2)", color=:darkgreen, lw=2.5)
# Нанесем стационарные уровни в виде горизонтальных пунктирных линий
hline!(plt1, [M_stationary[1]], linestyle=:dash, color=:blue, alpha=0.6, label="Асимптота M1")
hline!(plt1, [M_stationary[2]], linestyle=:dash, color=:darkgreen, alpha=0.6, label="Асимптота M2")
title!(plt1, "Случай 1: Чистая рыночная конкуренция")
xaxis!(plt1, "Безразмерное время θ")
yaxis!(plt1, "Оборотные средства M")

# График 2: Случай 2
plt2 = plot(sol2, vars=(0, 1), label="Фирма 1 (M1 - под давлением)", color=:blue, lw=2.5)
plot!(plt2, sol2, vars=(0, 2), label="Фирма 2 (M2 - стабильная)", color=:darkgreen, lw=2.5)
title!(plt2, "Случай 2: Влияние социально-психологического фактора")
xaxis!(plt2, "Безразмерное время θ")
yaxis!(plt2, "Оборотные средства M")

# Объединение в финальный коллаж
final_plot = plot(plt1, plt2, layout=(2, 1), size=(800, 700))

# Показ и автоматическое сохранение графика в папку plots
display(final_plot)
savefig(final_plot, plotsdir("firms_competition_report.png"))
println("Графики успешно сохранены в файл: ", plotsdir("firms_competition_report.png"))
